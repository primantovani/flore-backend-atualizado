DECLARE
    V_ANA NUMBER; V_BIA NUMBER; V_I1 NUMBER; V_I2 NUMBER; V_I3 NUMBER;
BEGIN
    INSERT INTO USERS (EMAIL, PASSWORD, NOME) VALUES ('ana@flore.demo', 'x', 'Ana Souza') RETURNING ID INTO V_ANA;
    INSERT INTO USERS (EMAIL, PASSWORD, NOME) VALUES ('bia@flore.demo', 'x', 'Bia Lima') RETURNING ID INTO V_BIA;
    INSERT INTO CLOSET_ITEMS (ITEM_NAME, CATEGORY, PRICE, OWNER_ID) VALUES ('Vestido floral midi', 'vestido', 89.90, V_ANA) RETURNING ID INTO V_I1;
    INSERT INTO CLOSET_ITEMS (ITEM_NAME, CATEGORY, PRICE, OWNER_ID) VALUES ('Jaqueta jeans', 'casaco', 120.00, V_ANA) RETURNING ID INTO V_I2;
    INSERT INTO CLOSET_ITEMS (ITEM_NAME, CATEGORY, PRICE, OWNER_ID) VALUES ('Saia plissada', 'saia', 55.00, V_ANA) RETURNING ID INTO V_I3;
    PKG_FLORE.REGISTRAR_PEDIDO(V_I1, V_BIA, 'Sao Paulo');
    PKG_FLORE.REGISTRAR_PEDIDO(V_I2, V_BIA, 'Curitiba');
    PKG_FLORE.REGISTRAR_PEDIDO(V_I3, V_BIA, 'Sao Paulo');
    UPDATE PEDIDOS SET STATUS = 'EM_TRANSITO', RISCO_CLIMATICO = 'S' WHERE CLOSET_ITEM_ID = V_I1;
    UPDATE PEDIDOS SET STATUS = 'ENTREGUE' WHERE CLOSET_ITEM_ID = V_I2;
END;
