PROMPT ===== 2.2 TRIGGER DE AUDITORIA =====
PROMPT UPDATE CLOSET_ITEMS SET ITEM_STATUS = 'SOLD' (Vestido floral midi e Jaqueta jeans)
UPDATE CLOSET_ITEMS SET ITEM_STATUS = 'SOLD' WHERE ITEM_NAME IN ('Vestido floral midi', 'Jaqueta jeans');
PROMPT Registros gravados automaticamente pela trigger TRG_AUDITORIA_CLOSET:
SELECT A.CLOSET_ITEM_ID, C.ITEM_NAME AS PECA, A.STATUS_ANTERIOR, A.STATUS_NOVO,
       TO_CHAR(A.DATA_ALTERACAO, 'DD/MM/YYYY HH24:MI') AS DATA_ALTERACAO, A.USUARIO_BANCO
FROM AUDITORIA_CLOSET_ITEMS A JOIN CLOSET_ITEMS C ON C.ID = A.CLOSET_ITEM_ID
ORDER BY A.ID;

