PROMPT ===== 2.1 PACKAGE PKG_FLORE =====
PROMPT Objetos da Parte 1 no banco (todos devem estar VALID):
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
WHERE OBJECT_NAME IN ('PKG_FLORE', 'TRG_AUDITORIA_CLOSET', 'PR_CONSULTAR_PEDIDOS_DINAMICO')
ORDER BY OBJECT_NAME, OBJECT_TYPE;
PROMPT Erros de compilação (USER_ERRORS):
SELECT COUNT(*) AS ERROS FROM USER_ERRORS
WHERE NAME IN ('PKG_FLORE', 'TRG_AUDITORIA_CLOSET', 'PR_CONSULTAR_PEDIDOS_DINAMICO');
PROMPT Chamadas pelo package:
SELECT PKG_FLORE.PERCENTUAL_PEDIDOS_STATUS('EM_TRANSITO') AS PCT_EM_TRANSITO,
       PKG_FLORE.PERCENTUAL_PEDIDOS_STATUS('ENTREGUE') AS PCT_ENTREGUE FROM DUAL;
SELECT PKG_FLORE.RESUMO_PEDIDO(MIN(ID)) AS RESUMO FROM PEDIDOS;

