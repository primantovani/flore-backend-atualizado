-- Functions e procedures da Fase 6. CREATE OR REPLACE: seguro rodar a cada deploy.

CREATE OR REPLACE FUNCTION FN_PERCENTUAL_PEDIDOS_STATUS (
    P_STATUS IN VARCHAR2
) RETURN NUMBER
IS
    V_TOTAL  NUMBER;
    V_STATUS NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_TOTAL FROM PEDIDOS;

    SELECT COUNT(*) INTO V_STATUS
    FROM PEDIDOS
    WHERE STATUS = UPPER(P_STATUS);

    IF V_TOTAL = 0 THEN
        RETURN 0;
    END IF;

    RETURN ROUND((V_STATUS / V_TOTAL) * 100, 2);
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END;
/

CREATE OR REPLACE FUNCTION FN_RESUMO_PEDIDO (
    P_PEDIDO_ID IN NUMBER
) RETURN VARCHAR2
IS
    V_RESUMO VARCHAR2(4000);
BEGIN
    SELECT
        'Pedido #' || P.ID ||
        ' | Comprador: ' || U.NOME ||
        ' | Item: ' || C.ITEM_NAME ||
        ' | Destino: ' || P.CIDADE_DESTINO ||
        ' | Status: ' || P.STATUS ||
        ' | Risco climático: ' ||
        CASE WHEN P.RISCO_CLIMATICO = 'S' THEN 'SIM' ELSE 'NAO' END
    INTO V_RESUMO
    FROM PEDIDOS P
    INNER JOIN USERS U ON U.ID = P.COMPRADOR_ID
    INNER JOIN CLOSET_ITEMS C ON C.ID = P.CLOSET_ITEM_ID
    WHERE P.ID = P_PEDIDO_ID;

    RETURN V_RESUMO;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Pedido nao encontrado.';
    WHEN TOO_MANY_ROWS THEN
        RETURN 'Erro: mais de um pedido encontrado.';
    WHEN OTHERS THEN
        RETURN 'Erro ao gerar resumo do pedido.';
END;
/

CREATE OR REPLACE PROCEDURE PR_REGISTRAR_PEDIDO (
    P_CLOSET_ITEM_ID IN NUMBER,
    P_COMPRADOR_ID   IN NUMBER,
    P_CIDADE_DESTINO IN VARCHAR2
)
IS
    V_STATUS_ITEM CLOSET_ITEMS.ITEM_STATUS%TYPE;
    V_USUARIO     NUMBER;
    V_PEDIDO_ID   NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_USUARIO
    FROM USERS
    WHERE ID = P_COMPRADOR_ID;

    IF V_USUARIO = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Comprador nao encontrado.');
    END IF;

    BEGIN
        SELECT ITEM_STATUS INTO V_STATUS_ITEM
        FROM CLOSET_ITEMS
        WHERE ID = P_CLOSET_ITEM_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20002, 'Peca nao encontrada.');
    END;

    IF V_STATUS_ITEM <> 'AVAILABLE' THEN
        RAISE_APPLICATION_ERROR(-20003, 'A peca nao esta disponivel para compra.');
    END IF;

    INSERT INTO PEDIDOS (
        CLOSET_ITEM_ID, COMPRADOR_ID, STATUS, CIDADE_DESTINO,
        DATA_PEDIDO, DATA_PREVISTA_ENTREGA, RISCO_CLIMATICO
    )
    VALUES (
        P_CLOSET_ITEM_ID, P_COMPRADOR_ID, 'PENDENTE', P_CIDADE_DESTINO,
        SYSDATE, SYSDATE + 7, 'N'
    )
    RETURNING ID INTO V_PEDIDO_ID;

    DBMS_OUTPUT.PUT_LINE('Pedido criado com sucesso. ID: ' || V_PEDIDO_ID);
EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE PR_GERAR_ALERTAS_CLIMA
IS
    CURSOR C_PEDIDOS_RISCO IS
        SELECT ID, CIDADE_DESTINO, STATUS
        FROM PEDIDOS
        WHERE RISCO_CLIMATICO = 'S';

    V_EXISTE_ALERTA NUMBER;
BEGIN
    FOR PEDIDO IN C_PEDIDOS_RISCO LOOP
        SELECT COUNT(*) INTO V_EXISTE_ALERTA
        FROM ALERTAS_CLIMA
        WHERE PEDIDO_ID = PEDIDO.ID;

        IF V_EXISTE_ALERTA = 0 THEN
            INSERT INTO ALERTAS_CLIMA (PEDIDO_ID, DESCRICAO, DATA_ALERTA)
            VALUES (
                PEDIDO.ID,
                'Risco climatico identificado para entrega em ' || PEDIDO.CIDADE_DESTINO,
                SYSDATE
            );

            DBMS_OUTPUT.PUT_LINE('Alerta criado para o pedido ' || PEDIDO.ID);
        END IF;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END;
/
