-- Tabelas do Florê (Fase 6 - Database Programming).
-- Idempotente: o pipeline roda este script a cada deploy, entao uma tabela
-- que ja existe (ORA-00955) e ignorada em vez de derrubar a execucao.

DECLARE
    PROCEDURE criar(p_ddl IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_ddl;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE = -955 THEN
                NULL;
            ELSE
                RAISE;
            END IF;
    END;
BEGIN
    criar(q'[
        CREATE TABLE USERS (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            EMAIL VARCHAR2(255) NOT NULL,
            PASSWORD VARCHAR2(255) NOT NULL,
            NOME VARCHAR2(150) NOT NULL,
            CONSTRAINT PK_USERS PRIMARY KEY (ID),
            CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL)
        )]');

    criar(q'[
        CREATE TABLE CLOSET_ITEMS (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            ITEM_NAME VARCHAR2(150) NOT NULL,
            CATEGORY VARCHAR2(100) NOT NULL,
            PRICE NUMBER(10,2) NOT NULL,
            DESCRIPTION VARCHAR2(1000),
            ITEM_SIZE VARCHAR2(20),
            ITEM_STATUS VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
            OWNER_ID NUMBER NOT NULL,
            CONSTRAINT PK_CLOSET_ITEMS PRIMARY KEY (ID),
            CONSTRAINT FK_CLOSET_ITEMS_OWNER FOREIGN KEY (OWNER_ID) REFERENCES USERS (ID),
            CONSTRAINT CK_CLOSET_ITEMS_STATUS CHECK (ITEM_STATUS IN ('AVAILABLE', 'SOLD')),
            CONSTRAINT CK_CLOSET_ITEMS_PRICE CHECK (PRICE >= 0)
        )]');

    criar(q'[
        CREATE TABLE PEDIDOS (
            ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            CLOSET_ITEM_ID NUMBER NOT NULL,
            COMPRADOR_ID NUMBER NOT NULL,
            STATUS VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
            CIDADE_DESTINO VARCHAR2(100),
            DATA_PEDIDO DATE DEFAULT SYSDATE NOT NULL,
            DATA_PREVISTA_ENTREGA DATE,
            DATA_ENTREGA DATE,
            RISCO_CLIMATICO CHAR(1) DEFAULT 'N' NOT NULL,
            CONSTRAINT CK_PEDIDO_STATUS CHECK (STATUS IN ('PENDENTE', 'EM_TRANSITO', 'ENTREGUE', 'CANCELADO')),
            CONSTRAINT CK_PEDIDO_RISCO CHECK (RISCO_CLIMATICO IN ('S', 'N')),
            CONSTRAINT FK_PEDIDO_ITEM FOREIGN KEY (CLOSET_ITEM_ID) REFERENCES CLOSET_ITEMS (ID),
            CONSTRAINT FK_PEDIDO_COMPRADOR FOREIGN KEY (COMPRADOR_ID) REFERENCES USERS (ID)
        )]');

    criar(q'[
        CREATE TABLE ALERTAS_CLIMA (
            ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            PEDIDO_ID NUMBER NOT NULL,
            DESCRICAO VARCHAR2(200) NOT NULL,
            DATA_ALERTA DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT FK_ALERTA_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDOS (ID)
        )]');
END;
/
