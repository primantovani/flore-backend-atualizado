-- Fase 7 - Parte 1 (Gabriel): package PKG_FLORE, que centraliza as rotinas da Fase 6.
-- CREATE OR REPLACE: seguro rodar a cada deploy.

CREATE OR REPLACE PACKAGE PKG_FLORE AS

    FUNCTION PERCENTUAL_PEDIDOS_STATUS(
        P_STATUS IN VARCHAR2
    ) RETURN NUMBER;

    FUNCTION RESUMO_PEDIDO(
        P_PEDIDO_ID IN NUMBER
    ) RETURN VARCHAR2;

    PROCEDURE REGISTRAR_PEDIDO(
        P_CLOSET_ITEM_ID IN NUMBER,
        P_COMPRADOR_ID   IN NUMBER,
        P_CIDADE_DESTINO IN VARCHAR2
    );

    PROCEDURE GERAR_ALERTAS_CLIMA;

END PKG_FLORE;
/

CREATE OR REPLACE PACKAGE BODY PKG_FLORE AS

    FUNCTION PERCENTUAL_PEDIDOS_STATUS(
        P_STATUS IN VARCHAR2
    ) RETURN NUMBER
    IS
    BEGIN
        RETURN FN_PERCENTUAL_PEDIDOS_STATUS(P_STATUS);
    END PERCENTUAL_PEDIDOS_STATUS;

    FUNCTION RESUMO_PEDIDO(
        P_PEDIDO_ID IN NUMBER
    ) RETURN VARCHAR2
    IS
    BEGIN
        RETURN FN_RESUMO_PEDIDO(P_PEDIDO_ID);
    END RESUMO_PEDIDO;

    PROCEDURE REGISTRAR_PEDIDO(
        P_CLOSET_ITEM_ID IN NUMBER,
        P_COMPRADOR_ID   IN NUMBER,
        P_CIDADE_DESTINO IN VARCHAR2
    )
    IS
    BEGIN
        PR_REGISTRAR_PEDIDO(
            P_CLOSET_ITEM_ID,
            P_COMPRADOR_ID,
            P_CIDADE_DESTINO
        );
    END REGISTRAR_PEDIDO;

    PROCEDURE GERAR_ALERTAS_CLIMA
    IS
    BEGIN
        PR_GERAR_ALERTAS_CLIMA;
    END GERAR_ALERTAS_CLIMA;

END PKG_FLORE;
/
